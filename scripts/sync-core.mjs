#!/usr/bin/env node
import {
  readFile,
  readdir,
  mkdir,
  writeFile,
  rm,
  stat,
} from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const sourceDir = join(root, "packages/core/src");
const targetRoots = [
  join(root, "plugins/shared-assets/shared/core"),
  join(root, "plugins/task-board/shared/core"),
];
const check = process.argv.includes("--check");

async function sourceFiles(directory, base = directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await sourceFiles(path, base)));
    else if (entry.isFile() && entry.name.endsWith(".ts"))
      files.push(relative(base, path));
  }
  return files;
}

function generated(file, content) {
  return `// @generated by scripts/sync-core.mjs from packages/core/src/${file}; do not edit.\n${content}`;
}

const files = await sourceFiles(sourceDir);
const expected = new Map();
for (const file of files) {
  expected.set(
    file,
    generated(file, await readFile(join(sourceDir, file), "utf8")),
  );
}

if (check) {
  const problems = [];
  for (const targetRoot of targetRoots) {
    const targetFiles = (await stat(targetRoot).catch(() => null))
      ? await sourceFiles(targetRoot)
      : [];
    for (const [file, content] of expected) {
      const actual = await readFile(join(targetRoot, file), "utf8").catch(
        () => null,
      );
      if (actual !== content) problems.push(`out of sync: ${file}`);
    }
    for (const file of targetFiles) {
      if (!expected.has(file)) problems.push(`stale generated file: ${file}`);
    }
  }
  if (problems.length > 0) {
    console.error("shared/core is not in sync. Run: npm run sync:core");
    for (const problem of problems) console.error(`- ${problem}`);
    process.exit(1);
  }
  console.log(`shared/core matches ${expected.size} source files`);
  process.exit(0);
}

for (const targetRoot of targetRoots) {
  await rm(targetRoot, { recursive: true, force: true });
  for (const [file, content] of expected) {
    const target = join(targetRoot, file);
    await mkdir(join(target, ".."), { recursive: true });
    await writeFile(target, content, "utf8");
  }
}
console.log(
  `synced ${expected.size} core files into ${targetRoots.length} plugins`,
);
