export const GENERATED_HEADER =
  "<!-- generated by agentstorm-shared-assets; edit .agentstorm/AGENTS.md -->";

async function readShared(
  cwd: string,
): Promise<{ content: string; digest: string } | null> {
  try {
    const content = await readFile(join(cwd, "AGENTS.md"), "utf8");
    return { content, digest: sha256(content) };
  } catch {
    return null;
  }
}

async function fileDigest(path: string): Promise<string | null> {
  try {
    return sha256(await readFile(path));
  } catch {
    return null;
  }
}

async function isOwnedEntry(
  targetPath: string,
  canonicalPath: string,
  record: InstructionProjection | undefined,
): Promise<{ owned: boolean; reason?: string }> {
  const info = await lstat(targetPath).catch(() => null);
  if (!info) return { owned: true };
  if (info.isSymbolicLink()) {
    const link = await readlink(targetPath).catch(() => "");
    const resolved = isAbsolute(link)
      ? link
      : resolve(dirname(targetPath), link);
    const [linkTarget, canonical] = await Promise.all([
      realpath(resolved).catch(() => resolved),
      realpath(canonicalPath).catch(() => canonicalPath),
    ]);
    return linkTarget === canonical
      ? { owned: true }
      : { owned: false, reason: "symlink points elsewhere" };
  }
  if (!info.isFile())
    return { owned: false, reason: "not a regular file or symlink" };
  const content = await readFile(targetPath, "utf8");
  if (content.startsWith(GENERATED_HEADER)) return { owned: true };
  const digest = sha256(content);
  if (record?.kind === "copy" && record.baselineDigest === digest)
    return { owned: true };
  return { owned: false, reason: "existing user file differs" };
}

export async function instructionStatus(
  projectId: string,
  workspaceDirectory: string,
): Promise<InstructionStatusResult> {
  const shared = await readShared(repoDir(projectId));
  const canonicalPath = join(workspaceDirectory, ".agentstorm", "AGENTS.md");
  const config = await readConfig();
  const stored = config.instructions[projectId];
  const canonicalExists = await fileExists(canonicalPath);
  const canonicalDigest = canonicalExists
    ? await fileDigest(canonicalPath)
    : null;
  const canonicalManaged =
    canonicalDigest !== null &&
    (canonicalDigest === stored?.canonical?.baselineDigest ||
      canonicalDigest === shared?.digest);

  const targets: InstructionTargetStatus[] = [];
  for (const provider of PROVIDERS) {
    const entrypoint = INSTRUCTION_ENTRYPOINTS[provider.id];
    if (!entrypoint) continue;
    const targetPath = join(workspaceDirectory, entrypoint);
    const record = stored?.providers.find(
      (entry) => entry.provider === provider.id,
    );
    if (provider.id !== "codex" && provider.id !== "claude" && !record) {
      continue;
    }
    if (!(await fileExists(targetPath))) {
      targets.push({
        provider: provider.id,
        targetPath,
        state: "absent",
        owned: false,
      });
      continue;
    }
    const ownership = await isOwnedEntry(targetPath, canonicalPath, record);
    targets.push({
      provider: provider.id,
      targetPath,
      state: ownership.owned ? "managed" : "conflict",
      owned: ownership.owned,
    });
  }

  return {
    sharedExists: shared !== null,
    sharedDigest: shared?.digest ?? null,
    canonical: {
      targetPath: canonicalPath,
      exists: canonicalExists,
      managed: canonicalManaged,
      matchesShared: shared !== null && canonicalDigest === shared.digest,
    },
    targets,
  };
}

async function writeCanonical(
  projectId: string,
  workspaceDirectory: string,
  content: string,
  digest: string,
): Promise<string> {
  const canonicalPath = join(workspaceDirectory, ".agentstorm", "AGENTS.md");
  await resolveInside(workspaceDirectory, canonicalPath);
  const config = await readConfig();
  const stored = config.instructions[projectId]?.canonical ?? null;
  if (await fileExists(canonicalPath)) {
    const current = await fileDigest(canonicalPath);
    if (current !== digest && current !== stored?.baselineDigest) {
      throw new PluginError(
        "E_VALIDATION_FAILED",
        `${canonicalPath} already exists with user content; resolve the conflict first`,
      );
    }
    if (current === digest) {
      await mkdir(dirname(canonicalPath), { recursive: true });
      return canonicalPath;
    }
  }
  await atomicWriteFile(canonicalPath, content);
  return canonicalPath;
}

async function createProviderEntry(
  provider: ProviderId,
  targetPath: string,
  canonicalPath: string,
  content: string,
  record: InstructionProjection | undefined,
): Promise<InstructionProjection> {
  await mkdir(dirname(targetPath), { recursive: true });
  const info = await lstat(targetPath).catch(() => null);
  if (info) {
    const ownership = await isOwnedEntry(targetPath, canonicalPath, record);
    const identical =
      info.isFile() && (await fileDigest(targetPath)) === sha256(content);
    if (!ownership.owned && !identical) {
      throw new PluginError(
        "E_VALIDATION_FAILED",
        `${targetPath} already exists with user content (${ownership.reason ?? "conflict"})`,
      );
    }
    const linkIsCorrect =
      info.isSymbolicLink() &&
      (await isOwnedEntry(targetPath, canonicalPath, record)).owned;
    if (linkIsCorrect) {
      return {
        provider,
        targetPath,
        kind: "symlink",
        baselineDigest: null,
        updatedAt: new Date().toISOString(),
      };
    }
    await rm(targetPath, { force: true });
  }

  const relativeLink = relative(dirname(targetPath), canonicalPath);
  try {
    await symlink(relativeLink, targetPath);
    return {
      provider,
      targetPath,
      kind: "symlink",
      baselineDigest: null,
      updatedAt: new Date().toISOString(),
    };
  } catch {
    const generated = `${GENERATED_HEADER}\n${content}`;
    const temporary = `${targetPath}.tmp-${process.pid}-${Date.now()}`;
    await writeFile(temporary, generated, "utf8");
    await rename(temporary, targetPath);
    return {
      provider,
      targetPath,
      kind: "copy",
      baselineDigest: sha256(generated),
      updatedAt: new Date().toISOString(),
    };
  }
}

export async function setInstructionsEnabled(input: {
  projectId: string;
  workspaceDirectory: string;
  provider: string;
  enabled: boolean;
}): Promise<{
  canonical: string;
  targets: InstructionTargetStatus[];
  kept: Array<{ targetPath: string; reason: string }>;
}> {
  const providers = expandProvider(input.provider);
  if (providers.length === 0) {
    throw new PluginError(
      "E_PROVIDER_UNSUPPORTED",
      `Unknown provider: ${input.provider}`,
    );
  }
  const shared = await readShared(repoDir(input.projectId));
  if (!shared) {
    throw new PluginError(
      "E_ASSET_NOT_FOUND",
      "The shared repository has no root AGENTS.md",
    );
  }
  const canonicalPath = join(
    input.workspaceDirectory,
    ".agentstorm",
    "AGENTS.md",
  );
  const config = await readConfig();
  const stored = (config.instructions[input.projectId] ??= {
    canonical: null,
    providers: [],
  });
  const kept: Array<{ targetPath: string; reason: string }> = [];

  if (input.enabled) {
    await writeCanonical(
      input.projectId,
      input.workspaceDirectory,
      shared.content,
      shared.digest,
    );
    stored.canonical = {
      targetPath: canonicalPath,
      baselineDigest: shared.digest,
      updatedAt: new Date().toISOString(),
    };
    await recordBaselineFromFile({
      workspaceDirectory: input.workspaceDirectory,
      assetId: "prompt",
      kind: "prompt",
      provider: null,
      relativePath: "AGENTS.md",
      sourcePath: join(repoDir(input.projectId), "AGENTS.md"),
    });
  } else if (!stored.canonical) {
    throw new PluginError(
      "E_NOT_CONFIGURED",
      "Shared instructions are not projected",
    );
  }

  for (const provider of providers) {
    const entrypoint = INSTRUCTION_ENTRYPOINTS[provider];
    if (!entrypoint) {
      throw new PluginError(
        "E_PROVIDER_UNSUPPORTED",
        `Provider ${provider} has no verified instruction entrypoint`,
      );
    }
    const targetPath = join(input.workspaceDirectory, entrypoint);
    const index = stored.providers.findIndex(
      (entry) => entry.provider === provider,
    );
    const record = index >= 0 ? stored.providers[index] : undefined;
    if (!input.enabled) {
      if (!record) {
        kept.push({ targetPath, reason: "not managed by this plugin" });
        continue;
      }
      const ownership = await isOwnedEntry(targetPath, canonicalPath, record);
      if (!ownership.owned) {
        kept.push({
          targetPath,
          reason: ownership.reason ?? "user content kept",
        });
        if (index >= 0) stored.providers.splice(index, 1);
        continue;
      }
      await rm(targetPath, { force: true });
      if (index >= 0) stored.providers.splice(index, 1);
      continue;
    }

    const entry = await createProviderEntry(
      provider,
      targetPath,
      canonicalPath,
      shared.content,
      record,
    );
    entry.updatedAt = new Date().toISOString();
    if (index >= 0) stored.providers[index] = entry;
    else stored.providers.push(entry);
  }

  await writeConfig(config);
  const status = await instructionStatus(
    input.projectId,
    input.workspaceDirectory,
  );
  return { canonical: canonicalPath, targets: status.targets, kept };
}

export async function removeInstructionProjections(
  projectId: string,
  workspaceDirectory: string,
): Promise<{ removed: string[]; preserved: string[] }> {
  const config = await readConfig();
  const stored = config.instructions[projectId];
  if (!stored) return { removed: [], preserved: [] };
  const canonicalPath = join(workspaceDirectory, ".agentstorm", "AGENTS.md");
  const removed: string[] = [];
  const preserved: string[] = [];
  for (const record of stored.providers) {
    if (!(await fileExists(record.targetPath))) {
      removed.push(record.targetPath);
      continue;
    }
    const ownership = await isOwnedEntry(
      record.targetPath,
      canonicalPath,
      record,
    );
    if (ownership.owned) {
      await rm(record.targetPath, { force: true });
      removed.push(record.targetPath);
    } else {
      preserved.push(record.targetPath);
    }
  }
  delete config.instructions[projectId];
  await writeConfig(config);
  return { removed, preserved };
}
